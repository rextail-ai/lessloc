// PATTERNS.md's tables: each `{kind}` shows its badge from kinds.mjs, so the doc cannot claim a kind stops when it does not.
const badge = k => `\`${k}\`${CHECKS[k] === 0 ? ' (tier 0)' : INTERRUPT.includes(k) ? ' (**stops**)' : ''}`;
export const renderCatalog = () => GROUPS.map(([g, name, intro], i) => {
  const rows = PATTERNS.filter(p => p.group === g), std = rows.some(p => p.standard);
  const head = std ? '| Pattern | Standard that calls it bad | lessloc |\n|---|---|---|' : `| ${g === 'context' ? 'Problem' : 'Pattern'} | lessloc |\n|---|---|`;
  const row = p => `| ${[p.title, ...(std ? [p.standard || '—'] : []), p.does.replace(/\{([a-z-]+)\}/g, (_, k) => badge(k))].join(' | ')} |`;
  return [`## ${i + 1}. ${name}`, intro, [head, ...rows.map(row)].join('\n')].filter(Boolean).join('\n\n');
}).join('\n\n');
